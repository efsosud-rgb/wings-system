import {
  bigint,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { tenants, WINGS_TENANT_ID } from './ads.js';
import { clientId } from './clients.js';
import { driveFiles } from './drive.js';
import { employees } from './employees.js';

const tenantId = () =>
  uuid('tenant_id')
    .notNull()
    .default(WINGS_TENANT_ID)
    .references(() => tenants.id);

export const integrationStateEnum = pgEnum('integration_state', [
  'disconnected',
  'pending',
  'connected',
  'needs_reconnect',
]);

/**
 * One row per external service the SYSTEM is connected to (not per person).
 *
 * Every credential column holds ciphertext from `secret-box.ts`: the access
 * token, the refresh token, the client secret when registration issues one,
 * and — while an authorization is pending — the device code or the PKCE
 * verifier. Nothing in this table is usable without INTEGRATIONS_ENCRYPTION_KEY.
 */
export const integrationConnections = pgTable(
  'integration_connections',
  {
    tenantId: tenantId(),
    id: uuid('id').primaryKey().defaultRandom(),
    provider: text('provider').notNull(),
    state: integrationStateEnum('state').notNull().default('disconnected'),
    /** From dynamic registration or the environment. An identifier, not a secret. */
    clientId: text('client_id'),
    clientSecretEnc: text('client_secret_enc'),
    accessTokenEnc: text('access_token_enc'),
    refreshTokenEnc: text('refresh_token_enc'),
    accessExpiresAt: timestamp('access_expires_at', { withTimezone: true }),
    scopes: text('scopes').array().notNull().default([]),
    /**
     * The authorization in progress. `secretEnc` is the device code or the PKCE
     * verifier, encrypted; the rest is what the screen may show.
     */
    pending: jsonb('pending'),
    /**
     * Kairogen only: the plan the account is on. `estimate_cost` demands it and
     * nothing reports it, so an Admin Master states it on the settings card.
     */
    plan: text('plan').notNull().default('free'),
    protocolVersion: text('protocol_version'),
    /** Tool names, descriptions and input schemas, read live after connecting. */
    tools: jsonb('tools').notNull().default([]),
    /** A code, never a provider message that could quote a credential. */
    lastError: text('last_error'),
    connectedBy: uuid('connected_by').references(() => employees.id),
    connectedAt: timestamp('connected_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex('integration_connections_provider_uq').on(table.tenantId, table.provider),
  ],
);

export const mediaOriginEnum = pgEnum('media_origin', ['kairogen', 'upload']);
export const mediaKindEnum = pgEnum('media_kind', ['image', 'video']);

/**
 * The media library: the seed of the Drive module.
 *
 * The file lives on the mounted volume (MEDIA_DIR) under `storageKey`; the
 * database keeps what it is and where it came from. A file is only ever served
 * through an authenticated route — there is no public address.
 */
export const mediaAssets = pgTable(
  'media_assets',
  {
    tenantId: tenantId(),
    id: uuid('id').primaryKey().defaultRandom(),
    ownerId: uuid('owner_id')
      .notNull()
      .references(() => employees.id),
    origin: mediaOriginEnum('origin').notNull(),
    kind: mediaKindEnum('kind').notNull(),
    mimeType: text('mime_type').notNull(),
    byteSize: bigint('byte_size', { mode: 'number' }).notNull(),
    sha256: text('sha256').notNull(),
    width: integer('width'),
    height: integer('height'),
    durationSeconds: integer('duration_seconds'),
    /** Relative to MEDIA_DIR. Generated by the server, never from a file name. */
    storageKey: text('storage_key').notNull(),
    /** Kairogen only. */
    prompt: text('prompt'),
    model: text('model'),
    credits: integer('credits'),
    externalGenerationId: text('external_generation_id'),
    /**
     * Kairogen only: the address the output was downloaded from. Kept so the
     * same picture can be handed back to Kairogen (as a reference, to upscale)
     * without publishing anything of ours.
     */
    sourceUrl: text('source_url'),
    /** The asset this one was made from: an upscale, an animation. */
    sourceAssetId: uuid('source_asset_id'),
    /**
     * The Drive file that holds the bytes. The library is a view over the Drive's
     * "Mídia" folders; null only on a row the volume-to-Drive script has not reached.
     */
    driveFileId: uuid('drive_file_id').references(() => driveFiles.id, { onDelete: 'set null' }),
    /** Who it is for. Filing of ours: never part of anything Kairogen is sent. */
    clientId: clientId(),
    /** The free-text label from before the `clients` table. No longer read or written. */
    client: text('client'),
    folder: text('folder'),
    tags: text('tags').array().notNull().default([]),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index('media_assets_created_idx').on(table.createdAt),
    index('media_assets_owner_idx').on(table.ownerId),
    index('media_assets_client_idx').on(table.clientId),
  ],
);

export const mediaGenerationStatusEnum = pgEnum('media_generation_status', [
  'estimated',
  'running',
  'saving',
  'succeeded',
  'failed',
  'refused',
  'unknown',
  'timed_out',
]);

/**
 * One row per estimate, which becomes the generation when somebody clicks.
 *
 * A generation cannot be asked for by its parameters, only by the id of a row
 * here in state `estimated`: that is how "never generate without estimate_cost
 * first" is a fact of the data model rather than a habit of the callers. The
 * parameters sent to Kairogen are the ones stored at estimate time.
 */
export const mediaGenerations = pgTable(
  'media_generations',
  {
    tenantId: tenantId(),
    id: uuid('id').primaryKey().defaultRandom(),
    requestedBy: uuid('requested_by')
      .notNull()
      .references(() => employees.id),
    operation: text('operation').notNull(),
    kind: mediaKindEnum('kind').notNull(),
    model: text('model'),
    prompt: text('prompt'),
    /** The validated request, as the person or the agent's card made it. */
    request: jsonb('request').notNull(),
    /** What estimate_cost was asked: the price-affecting half of the tool arguments. */
    priceArgs: jsonb('price_args').notNull().default({}),
    creditsEstimated: integer('credits_estimated').notNull(),
    creditsCharged: integer('credits_charged'),
    status: mediaGenerationStatusEnum('status').notNull().default('estimated'),
    /** Words for the screen. Never a provider message that could hold a secret. */
    detail: text('detail'),
    externalGenerationId: text('external_generation_id'),
    sourceAssetId: uuid('source_asset_id'),
    /** The agent's card that was clicked, when one was. */
    proposalId: uuid('proposal_id'),
    /** Who it is for. An upscale or an animation is for whoever its source was for. */
    clientId: clientId(),
    estimateExpiresAt: timestamp('estimate_expires_at', { withTimezone: true }).notNull(),
    startedAt: timestamp('started_at', { withTimezone: true }),
    nextPollAt: timestamp('next_poll_at', { withTimezone: true }),
    pollCount: integer('poll_count').notNull().default(0),
    finishedAt: timestamp('finished_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index('media_generations_requester_idx').on(table.requestedBy, table.createdAt),
    index('media_generations_status_idx').on(table.status),
  ],
);

/**
 * Append-only: every step of every generation, with who, when, what and how
 * many credits. Rows are inserted and never changed; the monthly and daily
 * ceilings are sums over this table.
 */
export const mediaCreditLedger = pgTable(
  'media_credit_ledger',
  {
    tenantId: tenantId(),
    id: uuid('id').primaryKey().defaultRandom(),
    /** Null only on `balance_changed` rows, which belong to no generation. */
    generationId: uuid('generation_id').references(() => mediaGenerations.id),
    employeeId: uuid('employee_id')
      .notNull()
      .references(() => employees.id),
    /** estimated, started, refused, unknown, succeeded, failed, timed_out, balance_changed */
    event: text('event').notNull(),
    operation: text('operation').notNull(),
    model: text('model'),
    prompt: text('prompt'),
    params: jsonb('params').notNull().default({}),
    creditsEstimated: integer('credits_estimated').notNull(),
    creditsCharged: integer('credits_charged'),
    /**
     * What this row adds to the credits counted against the ceilings: the
     * estimate when a generation starts, a correction when the real charge is
     * known, the estimate given back when Kairogen refused before charging.
     */
    creditsDelta: integer('credits_delta').notNull().default(0),
    externalGenerationId: text('external_generation_id'),
    clientId: clientId(),
    /**
     * What `get_credits` answered when this row was written, when it was asked.
     * Kairogen moves the balance for reasons of its own (renewals, bonuses): with
     * this column a jump can be placed between two rows instead of guessed at.
     */
    balanceReported: integer('balance_reported'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index('media_credit_ledger_employee_idx').on(table.employeeId, table.createdAt),
    index('media_credit_ledger_created_idx').on(table.createdAt),
  ],
);

/**
 * Every temporary public link ever issued. Kairogen needs a public address to
 * read a reference image, and the library has none: a link names one asset,
 * lives fifteen minutes, is signed, and leaves this row behind.
 */
export const mediaPublicLinks = pgTable('media_public_links', {
  tenantId: tenantId(),
  id: uuid('id').primaryKey().defaultRandom(),
  assetId: uuid('asset_id')
    .notNull()
    .references(() => mediaAssets.id),
  generationId: uuid('generation_id').references(() => mediaGenerations.id),
  issuedBy: uuid('issued_by')
    .notNull()
    .references(() => employees.id),
  purpose: text('purpose').notNull(),
  expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});
