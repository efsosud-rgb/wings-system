import {
  bigint,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { tenants, WINGS_TENANT_ID } from './ads.js';
import { employees } from './employees.js';

const tenantId = () =>
  uuid('tenant_id')
    .notNull()
    .default(WINGS_TENANT_ID)
    .references(() => tenants.id);

export const integrationStateEnum = pgEnum('integration_state', [
  'disconnected',
  'pending',
  'connected',
  'needs_reconnect',
]);

/**
 * One row per external service the SYSTEM is connected to (not per person).
 *
 * Every credential column holds ciphertext from `secret-box.ts`: the access
 * token, the refresh token, the client secret when registration issues one,
 * and — while an authorization is pending — the device code or the PKCE
 * verifier. Nothing in this table is usable without INTEGRATIONS_ENCRYPTION_KEY.
 */
export const integrationConnections = pgTable(
  'integration_connections',
  {
    tenantId: tenantId(),
    id: uuid('id').primaryKey().defaultRandom(),
    provider: text('provider').notNull(),
    state: integrationStateEnum('state').notNull().default('disconnected'),
    /** From dynamic registration or the environment. An identifier, not a secret. */
    clientId: text('client_id'),
    clientSecretEnc: text('client_secret_enc'),
    accessTokenEnc: text('access_token_enc'),
    refreshTokenEnc: text('refresh_token_enc'),
    accessExpiresAt: timestamp('access_expires_at', { withTimezone: true }),
    scopes: text('scopes').array().notNull().default([]),
    /**
     * The authorization in progress. `secretEnc` is the device code or the PKCE
     * verifier, encrypted; the rest is what the screen may show.
     */
    pending: jsonb('pending'),
    protocolVersion: text('protocol_version'),
    /** Tool names, descriptions and input schemas, read live after connecting. */
    tools: jsonb('tools').notNull().default([]),
    /** A code, never a provider message that could quote a credential. */
    lastError: text('last_error'),
    connectedBy: uuid('connected_by').references(() => employees.id),
    connectedAt: timestamp('connected_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex('integration_connections_provider_uq').on(table.tenantId, table.provider),
  ],
);

export const mediaOriginEnum = pgEnum('media_origin', ['kairogen', 'upload']);
export const mediaKindEnum = pgEnum('media_kind', ['image', 'video']);

/**
 * The media library: the seed of the Drive module.
 *
 * The file lives on the mounted volume (MEDIA_DIR) under `storageKey`; the
 * database keeps what it is and where it came from. A file is only ever served
 * through an authenticated route — there is no public address.
 */
export const mediaAssets = pgTable(
  'media_assets',
  {
    tenantId: tenantId(),
    id: uuid('id').primaryKey().defaultRandom(),
    ownerId: uuid('owner_id')
      .notNull()
      .references(() => employees.id),
    origin: mediaOriginEnum('origin').notNull(),
    kind: mediaKindEnum('kind').notNull(),
    mimeType: text('mime_type').notNull(),
    byteSize: bigint('byte_size', { mode: 'number' }).notNull(),
    sha256: text('sha256').notNull(),
    width: integer('width'),
    height: integer('height'),
    durationSeconds: integer('duration_seconds'),
    /** Relative to MEDIA_DIR. Generated by the server, never from a file name. */
    storageKey: text('storage_key').notNull(),
    /** Kairogen only. */
    prompt: text('prompt'),
    model: text('model'),
    credits: integer('credits'),
    externalGenerationId: text('external_generation_id'),
    /** The asset this one was made from: an upscale, an animation. */
    sourceAssetId: uuid('source_asset_id'),
    client: text('client'),
    folder: text('folder'),
    tags: text('tags').array().notNull().default([]),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index('media_assets_created_idx').on(table.createdAt),
    index('media_assets_owner_idx').on(table.ownerId),
  ],
);
